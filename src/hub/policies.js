'use strict';
// Single source of truth for storage access. The same declaration drives (a) the SQL below (sql/hub-policies.sql, generated),
// (b) the simulated Storage server used in tests. Roles come from app_metadata.hub_role in the JWT; app_metadata can only be
// set with a server key, never by the user. Nothing is granted to `anon`.
const SYM = '[A-Z0-9]{3,12}';
const NAMES = {
  // bucket hub: what the app/Worker may read
  hubManifest: '^(manifest\\.json|manifest\\.sig)$',
  hubMonth: `^fx/${SYM}/[0-9]{4}-[0-9]{2}\\.v[0-9]+\\.m1\\.gz$`,
  // bucket hub-raw: writer-only working area
  rawDay: `^raw/${SYM}/[0-9]{4}/[0-9]{2}/[0-9]{2}\\.[0-9a-f]{16}\\.bi5$`,
  rawState: `^state/${SYM}\\.json$`,
  rawCandidate: '^candidate/manifest\\.json$',
};
const any = (...k) => '(' + k.map(x => NAMES[x].replace(/^\^|\$$/g, '')).join('|') + ')';
const rx = (...k) => '^' + any(...k) + '$';
const W = 'hub_writer', R = 'hub_reader';
const POLICIES = [
  { name: 'hub_select', op: 'SELECT', bucket: 'hub', roles: [W, R], name_rx: rx('hubManifest', 'hubMonth') },
  { name: 'hub_insert', op: 'INSERT', bucket: 'hub', roles: [W], name_rx: rx('hubManifest', 'hubMonth') },
  { name: 'hub_update', op: 'UPDATE', bucket: 'hub', roles: [W], name_rx: NAMES.hubManifest },            // only the two mutable pointers
  { name: 'hub_delete', op: 'DELETE', bucket: 'hub', roles: [W], name_rx: NAMES.hubMonth },               // old month versions only, never the manifest
  { name: 'raw_select', op: 'SELECT', bucket: 'hub-raw', roles: [W], name_rx: rx('rawDay', 'rawState', 'rawCandidate') },
  { name: 'raw_insert', op: 'INSERT', bucket: 'hub-raw', roles: [W], name_rx: rx('rawDay', 'rawState', 'rawCandidate') },
  { name: 'raw_update', op: 'UPDATE', bucket: 'hub-raw', roles: [W], name_rx: rx('rawState', 'rawCandidate') },   // raw day files are immutable
  { name: 'raw_delete', op: 'DELETE', bucket: 'hub-raw', roles: [W], name_rx: NAMES.rawDay },            // repair of a corrupt day object only; state/candidate can never be deleted
];
const q = s => "'" + s.replace(/'/g, "''") + "'";
function sqlFor(p) {
  const role = `(auth.jwt() -> 'app_metadata' ->> 'hub_role') in (${p.roles.map(q).join(', ')})`;
  const cond = `bucket_id = ${q(p.bucket)} and ${role} and name ~ ${q(p.name_rx)}`;
  const clause = p.op === 'INSERT' ? `with check (${cond})` : p.op === 'UPDATE' ? `using (${cond}) with check (${cond})` : `using (${cond})`;
  return `create policy ${q(p.name).replace(/'/g, '"')} on storage.objects for ${p.op.toLowerCase()} to authenticated\n  ${clause};`;
}
function generateSql() {
  return ['-- GENERATED by scripts/gen-policies-sql.js from src/hub/policies.js. Do not edit by hand. NOT applied anywhere yet.',
    "-- Preconditions in the dedicated Hub project: sign-ups disabled; users hub-writer and hub-reader created with app_metadata.hub_role set via a server key.",
    "-- Buckets hub and hub-raw are created PRIVATE (public = false). `anon` gets no policy at all.",
    ...POLICIES.map(sqlFor)].join('\n') + '\n';
}
// Evaluate the same rules the database would (used by the simulated Storage server).
function allowed(op, bucket, name, role) {
  return POLICIES.some(p => p.op === op && p.bucket === bucket && p.roles.includes(role) && new RegExp(p.name_rx).test(name));
}
module.exports = { POLICIES, NAMES, generateSql, allowed, ROLES: { W, R } };
